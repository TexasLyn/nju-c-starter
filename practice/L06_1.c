/*
 * L06_1 · 输入以 -1 结束，找最大数及其出现次数
 *
 * 【题目】（经典题）
 *   不断读入整数，直到读入 -1 为止（-1 不算数据，是结束标志）。
 *   输出这些数里的最大值，以及最大值出现了几次。
 *
 * 【输入格式】
 *   若干整数，最后一个是 -1。例如：
 *   3 7 2 7 5 7 -1
 *
 * 【输出格式】
 *   两个整数，用空格分隔，末尾换行：
 *   7 3
 *
 * 【题目保证】
 *   至少有一个有效数据（-1 之前至少有一个数）。
 *
 * 【思路：边读边比】
 *   这是"边读边处理"的典型模式，不需要数组就能做：
 *
 *       int x;
 *       int max = -2147483648;      (先设成一个非常小的数)
 *       int cnt = 0;
 *
 *       scanf("%d", &x);
 *       while (x != -1) {
 *           if (x > max) {
 *               max = x;            (发现更大的，换掉)
 *               cnt = 1;            (计数重新从 1 开始)
 *           } else if (x == max) {
 *               cnt++;              (又遇到一个最大值)
 *           }
 *           scanf("%d", &x);        (读下一个)
 *       }
 *
 * 【⚠️ 两个关键点】
 *
 *   1. "读第一个"要写在循环【外面】，循环体【末尾】再读下一个。
 *      如果只写在循环体里，就没法在进循环前判断是不是 -1 了。
 *      这个"先读一次，循环里再读"的模式叫【读前预读】，很常用。
 *
 *   2. 发现更大值时，cnt 要【重置为 1】而不是忘记重置。
 *      因为之前统计的是旧最大值的次数，新最大值才刚开始统计。
 *      只写 max = x 而忘了 cnt = 1，答案就会错。
 *
 * 【关于初始 max 的值】
 *   设成 -2147483648 是 int 能表示的最小值，这样任何输入都会比它大。
 *   也可以设成 -1 之外的一个很小的数，或者干脆先读第一个数作为初始 max。
 *
 * 【⚠️ 比较用 >= 和用 > 的区别】
 *   这里必须用 > 判断"更大"，用 == 判断"相等"。
 *   不能写成 if (x >= max) cnt++; —— 那样每次遇到更大的数都会
 *   在同一个分支里既换 max 又加 cnt，逻辑就乱了。
 */

#include <stdio.h>

int main(void)
{
    int x;
    int max = -2147483647 - 1;   /* int 的最小值 */
    int cnt = 0;

    scanf("%d", &x);

    // TODO: 循环处理，直到 x 是 -1
    //       提示：末尾别忘了再 scanf 一次读下一个

    printf("%d %d\n", max, cnt);

    return 0;
}
