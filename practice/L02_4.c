/*
 * L02_4 · 把分钟数换算成年和天
 *
 * 【题目】（经典题）
 *   读入一个整数表示分钟数，把它换算成"几年零几天"，并输出。
 *
 *   换算规则：
 *       1 小时 = 60 分钟
 *       1 天   = 24 小时 = 1440 分钟
 *       1 年   = 365 天  = 525600 分钟
 *   不足一年的部分算成天，不足一天的部分直接扔掉。
 *
 * 【输入格式】
 *   一个整数分钟数，例如 1000000
 *
 * 【输出格式】
 *   两个整数，用空格分隔：年数 和 剩下的天数。
 *   例如 1000000 应输出：
 *   1 329
 *
 * 【怎么算出来的】
 *   第一步，看 1000000 分钟里能装下几个整年：
 *       1000000 / 525600 = 1        ← 整除，小数砍掉，所以是 1 年
 *
 *   第二步，看装完一整年之后还剩多少分钟：
 *       1000000 % 525600 = 474400   ← 取余数，余下的分钟
 *
 *   第三步，把剩下的分钟换算成天：
 *       474400 / 1440 = 329.44...   ← 整除，小数砍掉，所以是 329 天
 *
 *   所以输出 "1 329"。
 *
 * 【提示】
 *   就用上面这三步，三个变量：
 *
 *       years = total / 525600;
 *       rest  = total % 525600;
 *       days  = rest / 1440;
 *
 * 【输出格式要求】
 *   两个数之间用一个空格，末尾换行。
 */

#include <stdio.h>

int main(void)
{
    int total;

    scanf("%d", &total);

    // TODO 1: 声明 years, rest, days 三个变量
    int years,rest,days;
    // TODO 2: 按上面的公式算出来
    years = total / 525600;
    rest = total % 525600;
    days = rest / 1440;
    // TODO 3: 输出 "年数 天数"
    printf("%d %d \n",years,days);
    return 0;
}
