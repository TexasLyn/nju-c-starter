/*
 * L06_2 · 递推法算 sin(x) 的幂级数展开
 *
 * 【题目】（经典题）
 *   用幂级数展开计算 sin(x)，直到通项的绝对值小于 1e-8 为止。
 *
 * 【公式】
 *   sin(x) = x - x³/3! + x⁵/5! - x⁷/7! + ...
 *
 * 【输入格式】
 *   一个浮点数 x（单位是【弧度】，不是角度）。
 *
 * 【输出格式】
 *   保留 8 位小数，占一行。
 *
 * 【样例】
 *   输入 1        →  0.84147098
 *   输入 0        →  0.00000000
 *   输入 1.5707963 → 1.00000000   （约等于 π/2）
 *
 * 【⚠️ 关键：不要一项一项从头算阶乘】
 *   直接算 x^7/7! 需要算 7!，算到第 20 项时 20! 已经是个天文数字，
 *   long 都装不下会溢出，结果全错。
 *
 *   【正确做法：递推】后一项可以由前一项乘一个简单的因子得到。
 *
 *   设第 k 项（从 0 开始计数）是 T_k = (-1)^k · x^(2k+1) / (2k+1)!
 *   那么：
 *       T_0 = x
 *       T_{k+1} / T_k = -x² / [(2k+2)(2k+3)]
 *   所以：
 *       T_{k+1} = -T_k · x² / [(2k+2)(2k+3)]
 *
 *   这样每一项只需要几次乘除，永远不会溢出。
 *
 * 【代码骨架】
 *
 *       double term = x;        (第一项)
 *       double sum  = x;        (累加和，先把第一项放进去)
 *       int k = 0;
 *
 *       while (fabs(term) >= 1e-8) {
 *           term = -term * x * x / ((2*k + 2) * (2*k + 3));
 *           sum  = sum + term;
 *           k++;
 *       }
 *
 * 【⚠️ 三个容易出错的地方】
 *
 *   1. sum 的初始值必须包含第一项 x，不能是 0。
 *      循环体里算的是【下一项】并加进去，第一项在循环外就要放好。
 *      如果写成 sum = 0，答案会少掉 x 这一项。
 *
 *   2. 循环条件用 fabs（浮点绝对值），不是 abs。
 *      abs 会把小数截断成整数，1e-8 会变成 0，循环立即退出。
 *
 *   3. 边界情况：x = 0 时第一项就是 0，fabs(0) >= 1e-8 不成立，
 *      循环一次都不执行，sum 保持 0，输出 0.00000000。这是正确的。
 */

