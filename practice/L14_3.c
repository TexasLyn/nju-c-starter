/*
 * L14_3 · 数字子串前插入 '-' 并写入文件
 *
 * 【题目】（经典题）
 *   读入一行字符串。在每一个【数字子串】前面插入一个 '-' 号。
 *   把结果写入文件 data.txt，同时打印到屏幕。
 *
 * 【什么是"数字子串"】
 *   连续的数字字符算一个数字子串。
 *   例如 "ab123cd45" 里有两个数字子串："123" 和 "45"。
 *
 * 【输入格式】
 *   一行字符串，长度不超过 200。
 *
 * 【输出格式】
 *   处理后的字符串，占一行（屏幕和 data.txt 内容相同）。
 *
 * 【样例】
 *   输入：ab123cd45
 *   输出：ab-123cd-45
 *
 *   输入：abc
 *   输出：abc            （没有数字，原样输出）
 *
 *   输入：123
 *   输出：-123           （开头就是数字，也要加 -）
 *
 *   输入：1a2b3
 *   输出：-1a-2b-3
 *
 * 【实现函数】
 *   题目原题要求实现函数：
 *
 *       char *insert(char *p)
 *
 *   它接收原字符串，返回处理后的字符串。
 *
 * 【思路：扫描 + 判断"数字子串的开头"】
 *
 *   关键判断：什么时候该插入 '-'？
 *   答：【当前位置是数字，并且前一个位置不是数字】（或者当前位置是开头）。
 *   这就是"数字子串的第一个字符"。
 *
 *       char buf[512];
 *       int k = 0;
 *
 *       for (int i = 0; p[i] != '\0'; i++) {
 *           int isDigit = (p[i] >= '0' && p[i] <= '9');
 *           int prevIsDigit = (i > 0 && p[i-1] >= '0' && p[i-1] <= '9');
 *
 *           if (isDigit && !prevIsDigit) {       (数字子串的开头)
 *               buf[k] = '-';
 *               k++;
 *           }
 *
 *           buf[k] = p[i];
 *           k++;
 *       }
 *       buf[k] = '\0';
 *
 *   🔸 “数字子串的开头”这个判断方法非常重要，是字符串处理题的常见套路。
 *      类似的还有“单词的开头”（第 12 课 L12_1 用过）。
 *
 * 【⚠️ 三个关键点】
 *
 *   1. `i > 0 &&` 这个条件不能漏。
 *      判断 p[i-1] 时，如果 i == 0，p[-1] 就【越界】了！
 *      C 的 && 有短路特性（第 4 课讲过），所以
 *      `i > 0 && p[i-1] >= '0'` 在 i == 0 时不会去读 p[-1]，是安全的。
 *
 *      🔸 【善用短路保护越界】是 C 里很重要的技巧。
 *
 *   2. 结果要写到另一个缓冲区 buf，不能原地改。
 *      因为插入 '-' 会让字符串变长，原地改会覆盖还没处理的内容。
 *      （这和 L12_2 的子串替换是同一个道理。）
 *
 *   3. buf 的末尾要补 '\0'。
 *
 * 【怎么返回字符串】
 *   函数签名是 `char *insert(char *p)`，要返回字符串。
 *   两种做法：
 *
 *   做法 A：返回传入的 buf 的地址（buf 必须是 static 或全局）
 *       static char buf[512];
 *       ...
 *       return buf;
 *      ⚠️ 如果 buf 是普通局部数组，函数返回后它就消失了，
 *         返回它的地址是【悬空指针】（第 9 课讲过）。
 *
 *   做法 B：把结果写回 p 自己（如果 p 的缓冲区够大）
 *       strcpy(p, buf);
 *       return p;
 *      这个更简单，但要保证 p 有足够空间放变长后的结果。
 *      本题 p 是 main 里的大数组，够用。
 *
 *   题目原题用的是做法 A 的思路。下面我们按做法 B 写（更安全），
 *   你在理解时可以两种都想想。
 */

