/*
 * L10_1 · 统计数组中有多少不相同的数据
 *
 * 【题目】（经典题）
 *   读入 n 个整数，统计其中有多少个【不相同】的数据。
 *
 * 【输入格式】
 *   第一行一个整数 n（1 <= n <= 100）
 *   第二行 n 个整数，用空格分隔
 *
 * 【输出格式】
 *   一个整数，占一行：不同数据的个数。
 *
 * 【样例】
 *   输入：
 *   10
 *   1 4 2 3 4 1 2 5 5 9
 *   输出：
 *   6
 *
 *   解释：出现过的数据有 1、4、2、3、5、9，共 6 种。
 *
 * 【思路：对每个元素，看它前面有没有出现过】
 *
 *   这是数组题最常用的套路。走一遍样例：
 *       第 0 个 1：前面没有 → 新数据，计数 1
 *       第 1 个 4：前面（1）里没有 4 → 新数据，计数 2
 *       第 2 个 2：前面（1,4）里没有 2 → 新数据，计数 3
 *       第 3 个 3：前面（1,4,2）里没有 3 → 新数据，计数 4
 *       第 4 个 4：前面有 4（下标 1）→ 跳过
 *       第 5 个 1：前面有 1（下标 0）→ 跳过
 *       第 6 个 2：前面有 2（下标 2）→ 跳过
 *       第 7 个 5：前面没有 5 → 新数据，计数 5
 *       第 8 个 5：前面有 5（下标 7）→ 跳过
 *       第 9 个 9：前面没有 9 → 新数据，计数 6
 *
 * 【代码结构】
 *
 *       int count = 0;
 *
 *       for (int i = 0; i < n; i++) {
 *           int seen = 0;                  (先假设"前面没见过")
 *
 *           for (int j = 0; j < i; j++) {  (只看 i 前面的)
 *               if (a[j] == a[i]) {
 *                   seen = 1;              (找到了，推翻假设)
 *                   break;                 (不用再找了)
 *               }
 *           }
 *
 *           if (!seen) {
 *               count++;                   (前面确实没有，是新数据)
 *           }
 *       }
 *
 * 【⚠️ 三个容易写错的地方】
 *
 *   1. 内层循环的终点是 i，不是 n。
 *      写 j < n 会把整个数组都比一遍（包括 i 自己），
 *      那样 a[i] == a[i] 永远成立，seen 永远是 1，结果永远是 0。
 *
 *   2. 变量 seen 必须在内层循环【外面】、外层循环【里面】声明。
 *      写在更外面的话，一轮结束后 seen=1 不会重置，后面全算"见过"。
 *
 *   3. 找到之后 break 是好习惯（省时间），但别忘了一开始就把 seen 设成 0。
 *
 * 【为什么用 `seen` 这个标志变量】
 *   这是第 5 课学过的"先假设成立，发现问题就推翻"的模式，
 *   和素数判断是同一个套路。回忆一下：
 *       int flag = 1;                  (先假设"是")
 *       for (...) if (反例) { flag = 0; break; }
 *       if (flag) { ... }
 */

#include <stdio.h>

#define MAXN 100

int main(void)
{
    int n;
    int a[MAXN];
    int count = 0;

    scanf("%d", &n);
    for (int i = 0; i < n; i++) {
        scanf("%d", &a[i]);
    }

    // TODO: 对每个元素，检查它前面有没有出现过；没出现过就 count++

    printf("%d\n", count);

    return 0;
}
