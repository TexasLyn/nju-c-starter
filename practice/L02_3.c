/*
 * L02_3 · 求一个整数的各位数字之和
 *
 * 【题目】（经典题）
 *   读入一个 0 到 1000 之间的整数，求它各位数字相加的和。
 *
 * 【输入格式】
 *   一个整数，例如 123
 *
 * 【输出格式】
 *   一个整数，占一行。例如 123 应输出：
 *   6
 *
 * 【提示】
 *   这是"拆数字"的入门题，只用两招：
 *
 *       个位 = n % 10
 *       去掉个位 = n / 10
 *
 *   比如 123：
 *       123 % 10 = 3          ← 拿到个位
 *       123 / 10 = 12         ← 去掉个位（注意是整数除法，小数被砍掉）
 *       12 % 10  = 2          ← 拿到十位
 *       12 / 10  = 1          ← 只剩百位
 *       1 % 10   = 1          ← 拿到百位
 *       和 = 3 + 2 + 1 = 6
 *
 * 【注意】
 *   题目说输入在 0~1000 之间，所以最多 4 位数。你可以只处理到千位，
 *   也可以用一个循环自动处理任意位数——两种写法都对。
 *   循环的写法第 5 课才学，这题先手动写 4 行。
 */

#include <stdio.h>

int main(void)
{
    int n;
    int sum = 0;

    scanf("%d", &n);

    // TODO: 用 % 和 / 把各位数字取出来，累加到 sum 里
    sum = sum + n%10;
    n = n/10;
    sum = sum + n%10;
    n = n/10;
    sum = sum + n%10;
    n = n/10;

    printf("%d\n", sum);

    return 0;
}
