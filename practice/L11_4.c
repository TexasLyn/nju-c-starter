/*
 * L11_4 · 统计字符串中各字母频率（不分大小写）
 *
 * 【题目】（经典题）
 *   读入一行字符串，统计其中每个【英文字母】出现的次数。
 *   大写和小写算同一个字母（'A' 和 'a' 都算 a）。
 *   只输出出现过的字母，按字母表顺序 a 到 z。
 *
 * 【输入格式】
 *   一行字符串，长度不超过 200，可能包含空格和标点。
 *
 * 【输出格式】
 *   每个出现过的字母一行，格式 "字母:次数"（小写字母）。
 *
 * 【样例】
 *   输入：
 *   Hello, World!
 *   输出：
 *   d:1
 *   e:1
 *   h:1
 *   l:3
 *   o:2
 *   r:1
 *   w:1
 *
 * 【样例分析】
 *   "Hello, World!" 里的字母（不分大小写）：
 *       H→h, e, l, l, o, W→w, o, r, l, d
 *   统计：
 *       d:1   e:1   h:1   l:3   o:2   r:1   w:1
 *   标点和空格不计。
 *
 * 【读一行字符串】
 *   ⚠️ 不能用 scanf("%s")，因为它遇到空格就停，只能读到一个单词。
 *   要用 fgets 读一整行：
 *
 *       char s[205];
 *       fgets(s, 205, stdin);
 *
 *   ⚠️ fgets 会把末尾的换行符也读进去，通常要去掉：
 *       s[strcspn(s, "\n")] = '\0';
 *   （strcspn 在 string.h 里，作用是"找出 \n 第一次出现的位置"。
 *     第 12 课会详细讲。加上这一句更保险，不加一般也能过。）
 *
 * 【核心技巧：用数组当计数器】
 *
 *   int freq[26] = {0};        (26 个字母各一个计数格)
 *
 *   for (int i = 0; s[i] != '\0'; i++) {       (遍历到字符串结束)
 *       char c = s[i];
 *
 *       if (c >= 'a' && c <= 'z') {
 *           freq[c - 'a']++;                   (小写：'a'→0, 'b'→1, ...)
 *       } else if (c >= 'A' && c <= 'Z') {
 *           freq[c - 'A']++;                   (大写也映射到同一个格子)
 *       }
 *       (其他字符（标点、空格、数字）不管)
 *   }
 *
 * 【⚠️ 为什么 c - 'a' 能当下标】
 *   在 C 里，字符【就是数字】（ASCII 码）：
 *       'a' = 97,  'b' = 98,  'c' = 99, ...  'z' = 122
 *       'A' = 65,  'B' = 66, ...             'Z' = 90
 *
 *   所以：
 *       'a' - 'a' = 0
 *       'b' - 'a' = 1
 *       'z' - 'a' = 25
 *   正好是 0 到 25 的下标，perfect 对应 freq[26]。
 *
 *   大写：'A' - 'A' = 0，'a' - 'a' = 0，两者都是 0。
 *   所以 freq[c - 'A'] 和 freq[c - 'a'] 在大写字母上结果一样，
 *   这就是"不分大小写"的实现方式。
 *
 * 【⚠️ 两个容易错的地方】
 *
 *   1. 忘了判断范围，直接 freq[c - 'a']++。
 *      如果 c 是空格（ASCII 32）或标点，c - 'a' 会是负数，
 *      那就【越界】访问数组了！必须先用 if 限制范围。
 *
 *   2. 遍历的终止条件是 s[i] != '\0'，不是 i < strlen(s)。
 *      两种都行，但前者更符合 C 的习惯，也不用调 strlen。
 *
 * 【输出】
 *   只有 freq[i] > 0 的才输出：
 *       for (int i = 0; i < 26; i++) {
 *           if (freq[i] > 0) {
 *               printf("%c:%d\n", 'a' + i, freq[i]);
 *           }
 *       }
 *   注意用 'a' + i 把下标变回字母。
 *
 * 【本题和第 10 课第 3 题的关系】
 *   第 10 课那道题是"用两个数组统计各数据出现次数"，
 *   本质一样，但这里用了一个巧妙的办法：
 *   【用字母本身当索引，就不需要"查找"了，直接定位】。
 *   这叫"桶计数"或"计数排序"的思想，非常常用。
 */

#include <stdio.h>
#include <string.h>

int main(void)
{
    char s[205];
    int freq[26] = {0};

    fgets(s, 205, stdin);
    s[strcspn(s, "\n")] = '\0';

    // TODO: 遍历字符串，统计每个字母的出现次数（不分大小写）

    // 输出
    for (int i = 0; i < 26; i++) {
        if (freq[i] > 0) {
            printf("%c:%d\n", 'a' + i, freq[i]);
        }
    }

    return 0;
}
