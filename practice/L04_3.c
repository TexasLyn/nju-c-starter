/*
 * L04_3 · 奖金提成（if 和 switch 各写一遍）
 *
 * 【题目】（经典题）
 *   企业发放的奖金根据利润提成。利润 p（整数）与提成规则如下：
 *
 *       p <= 100000            奖金 = p × 10%
 *       100000 < p <= 200000   奖金 = 100000×10% + (p-100000)×7.5%
 *       200000 < p <= 400000   奖金 = 17500 + (p-200000)×5%
 *       400000 < p <= 600000   奖金 = 27500 + (p-400000)×3%
 *       600000 < p <= 1000000  奖金 = 33500 + (p-600000)×1.5%
 *       p > 1000000            奖金 = 39500 + (p-1000000)×1%
 *
 *   （17500 = 10000 + 7500，是前两档的上限值；其余同理）
 *
 * 【输入格式】
 *   一个整数利润，例如 150000
 *
 * 【输出格式】
 *   两个整数，用空格分隔：用 if 算出的奖金 和 用 switch 算出的奖金。
 *   末尾换行。
 *
 * 【为什么要输出两个】
 *   这道题原题要求"用 if 和 switch 各写一遍"。把两个结果都打印出来，
 *   只要它们一致，就说明你两种写法都对了。这是一次自我检验。
 *
 *   比如输入 50000，两个结果都是 5000，输出：
 *   5000 5000
 *
 * 【第一步：用 if 实现】
 *   从高到低判断，或者从低到高累加，两种都行。从高到低更直观：
 *
 *       if (p > 1000000)      bonus1 = 39500 + (p - 1000000) * 0.01;
 *       else if (p > 600000)  bonus1 = 33500 + (p - 600000) * 0.015;
 *       else if (p > 400000)  bonus1 = 27500 + (p - 400000) * 0.03;
 *       else if (p > 200000)  bonus1 = 17500 + (p - 200000) * 0.05;
 *       else if (p > 100000)  bonus1 = 10000 + (p - 100000) * 0.075;
 *       else                  bonus1 = p * 0.10;
 *
 * 【第二步：用 switch 实现】
 *   switch 不能写范围判断，所以要用一个技巧：
 *   先做整除，把连续的利润范围压成几个整数。
 *
 *       switch (p / 100000) {
 *           case 0:  ... break;      // p < 100000
 *           case 1:  ... break;      // 100000 ~ 199999
 *           case 2:
 *           case 3:  ... break;      // 200000 ~ 399999 ← 故意穿透！
 *           ...
 *           default: ... break;      // p >= 1000000
 *       }
 *
 *   ⚠️ 注意 case 2 和 case 3 故意挨在一起不写 break，
 *      这就是上一节讲的"故意穿透"，让 2 和 3 共用同一段代码。
 *      这是 switch 的标准用法，不是错误。
 *
 * 【计算精度提示】
 *   算的时候用 double，最后赋值给 long 变量时会自动砍掉小数部分。
 *   题目给的例子里结果都是整数，所以不会有精度问题。
 *   变量类型用 long，因为利润可能很大。
 */

