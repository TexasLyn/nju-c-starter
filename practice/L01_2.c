/*
 * L01_2 · 输入 x，求 y = x*x + 2*x - 10
 *
 * 【题目】（经典题）
 *   从键盘读入一个整数 x，计算 y = x² + 2x − 10 并输出 y。
 *
 * 【输入格式】
 *   一个整数，例如 3
 *
 * 【输出格式】
 *   一个整数，占一行。例如输入 3 时应输出：
 *   5
 *
 * 【提示】
 *   - 读输入的那句 scanf 已经帮你写好了，你暂时不用管里面的 & 是什么，
 *     第 3 课会专门讲。现在只需要知道：想读一个整数到 x 里，就这么写。
 *   - 乘方在 C 里没有 ** 运算符，x² 就写成 x*x
 *   - 你要补的是：算出 y 的值，然后打印出来
 *
 * 【你要填的地方】
 *   1. 给 y 赋值
 *   2. 用 printf 把 y 打印出来
 */

#include <stdio.h>

int main(void)
{
    int x;
    int y = 0;

    // 这一句是"从键盘读入一个整数，存进 x"。现在照抄就行。
    scanf("%d", &x);

    // TODO 1: 把 y 算出来
    y = x*x + 2*x - 10;

    // TODO 2: 打印 y，末尾要换行
    printf("%d\n",y);

    return 0;
}
