/*
 * L04_2 · 三个数排序
 *
 * 【题目】（经典题）
 *   读入三个整数，按从小到大的顺序输出。
 *
 * 【输入格式】
 *   三个整数，用空格分隔。
 *
 * 【输出格式】
 *   三个整数，用空格分隔，末尾换行。
 *
 * 【样例】
 *   输入 3 1 2   →   1 2 3
 *
 * 【思路：用 if 做交换】
 *   C 里没有 Python 那种 a, b = b, a 的交换写法。要交换两个变量，
 *   必须借一个临时变量：
 *
 *       int t;
 *       t = a;      // 先把 a 存到临时变量里
 *       a = b;      // b 覆盖 a
 *       b = t;      // 再把存好的原 a 放回 b
 *
 *   画个图就明白了：
 *       开始:  a=3  b=1   t=?
 *       t=a:   a=3  b=1   t=3
 *       a=b:   a=1  b=1   t=3
 *       b=t:   a=1  b=1   t=3   → b 变成 3，交换完成
 *
 *   ⚠️ 如果写成 a = b; b = a; 会怎样？
 *       a=b:  a=1  b=1    原来的 3 已经丢了
 *       b=a:  a=1  b=1    还是 1，交换失败
 *   这就是为什么必须用临时变量。
 *
 * 【排序逻辑】
 *   三步就能排好三个数：
 *       if (a > b) 交换 a 和 b;      // 保证 a 是 a、b 中较小的
 *       if (a > c) 交换 a 和 c;      // 保证 a 是最小的
 *       if (b > c) 交换 b 和 c;      // 保证 c 是最大的
 *   走一遍 3 1 2：
 *       a=3,b=1,c=2
 *       a>b → 交换 → a=1,b=3,c=2
 *       a>c → 不换 → a=1,b=3,c=2
 *       b>c → 交换 → a=1,b=2,c=3   ✓
 */

