/*
 * L10_2 · 原地删除重复数据（不借助其他数组）
 *
 * 【题目】（经典题）
 *   读入 n 个整数，删除其中重复的数据，只保留每个数据第一次出现的位置。
 *   要求【不借助其他数组】，直接在原数组上操作。
 *
 * 【输入格式】
 *   第一行一个整数 n
 *   第二行 n 个整数
 *
 * 【输出格式】
 *   第一行：删除后剩下的数据个数
 *   第二行：剩下的数据，用空格分隔
 *
 * 【样例】
 *   输入：
 *   10
 *   1 4 2 3 4 1 2 5 5 9
 *   输出：
 *   6
 *   1 4 2 3 5 9
 *
 * 【核心技巧：双下标】
 *   用【两个下标】：
 *       i 负责"扫描"原数组（一直往前走）
 *       k 负责"记录写到哪里了"（只在存下新数据时前进）
 *
 *   关键认识：k 永远 <= i。
 *   也就是说，我们总是把后面的数据写到前面空出来的位置上，
 *   绝不会覆盖还没扫描到的数据。
 *
 *       int k = 0;                        (k 是"下一个该写的位置")
 *
 *       for (int i = 0; i < n; i++) {
 *           int seen = 0;
 *
 *           for (int j = 0; j < k; j++) { (只在【已保留的】里面找)
 *               if (a[j] == a[i]) {
 *                   seen = 1;
 *                   break;
 *               }
 *           }
 *
 *           if (!seen) {
 *               a[k] = a[i];              (写到 k 位置)
 *               k++;                      (k 前进一格)
 *           }
 *       }
 *       (结束后：a[0]..a[k-1] 就是结果，k 是结果个数)
 *
 * 【⚠️ 为什么内层循环是 j < k 而不是 j < i】
 *   这是本题最精妙的地方。
 *   j < i 也能得到正确答案，但 j < k 更快，
 *   因为 k 通常比 i 小（已经去掉了不少重复），比较次数更少。
 *   而且逻辑上更清楚：我只需要检查"已经决定保留的数据"里有没有重复。
 *
 * 🔸 画图理解（样例 1 4 2 3 4 1 2 5 5 9）：
 *
 *   i=0: a[0]=1，已保留区为空 → 存：a[0]=1，k=1
 *   i=1: a[1]=4，查 a[0..0]={1}，没有 4 → 存：a[1]=4，k=2
 *   i=2: a[2]=2，查 a[0..1]={1,4}，没有 2 → 存：a[2]=2，k=3
 *   i=3: a[3]=3，查 {1,4,2}，没有 3 → 存：a[3]=3，k=4
 *   i=4: a[4]=4，查 {1,4,2,3}，有 4 → 跳过
 *   i=5: a[5]=1，查 {1,4,2,3}，有 1 → 跳过
 *   i=6: a[6]=2，查 {1,4,2,3}，有 2 → 跳过
 *   i=7: a[7]=5，查 {1,4,2,3}，没有 5 → 存：a[4]=5，k=5  ← 注意写到下标 4
 *   i=8: a[8]=5，查 {1,4,2,3,5}，有 5 → 跳过
 *   i=9: a[9]=9，查 {1,4,2,3,5}，没有 9 → 存：a[5]=9，k=6
 *
 *   最后 a[0..5] = 1 4 2 3 5 9，k = 6  ✓
 *
 * 【⚠️ 最容易写错的地方】
 *   把 a[k] = a[i]; k++; 写反顺序，或者把 k++ 写在 if 外面：
 *
 *       if (!seen) {
 *           k++;                  (✗ 先加 k，会跳过一个位置)
 *           a[k] = a[i];
 *       }
 *
 *       if (!seen) { ... }
 *       k++;                      (✗ 无条件加，k 会一直等于 i，白做)
 *
 *   正确顺序是【先写，再前进】。
 */

#include <stdio.h>

#define MAXN 100

int main(void)
{
    int n;
    int a[MAXN];
    int k = 0;                  /* 已保留的数据个数，也是下一个可写位置 */

    scanf("%d", &n);
    for (int i = 0; i < n; i++) {
        scanf("%d", &a[i]);
    }

    // TODO: 用双下标原地去重

    printf("%d\n", k);

    for (int i = 0; i < k; i++) {
        printf("%d", a[i]);
        if (i < k - 1) {
            printf(" ");
        }
    }
    printf("\n");

    return 0;
}
