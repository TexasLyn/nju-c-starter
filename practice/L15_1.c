#include <stdio.h>
#include <string.h>

#define MAXN 100

/* 判断是不是字母 */
int is_letter(char c)
{
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z');
}

/* 提取所有以 e 结尾的单词，返回个数 */
/* TODO 1: 这一行参数里的列数有问题 */
int find_e_words(char *s, char words[][20])
{
    int n = 0;
    int i = 0;
    int len = (int)strlen(s);

    while (i < len) {
        /* 跳过非字母 */
        while (i < len && !is_letter(s[i])) {
            i++;
        }

        int start = i;

        /* 走到单词结尾（i 会停在单词后面第一格） */
        while (i < len && is_letter(s[i])) {
            i++;
        }

        /* TODO 2: 长度算多了一个字符 */
        int wlen = i - start + 1;

        /* TODO 3: 判断"以 e 结尾"用的下标不对 */
        if (wlen > 0 && s[i] == 'e') {
            for (int k = 0; k < wlen; k++) {
                words[n][k] = s[start + k];
            }

            /* TODO 4: 这一句补的不是字符串结束符 */
            words[n][wlen] = 'x';

            n++;
        }
    }

    return n;
}

int main(void)
{
    char s[400];
    char words[MAXN][20];
    int n;

    fgets(s, 400, stdin);
    s[strcspn(s, "\n")] = '\0';

    n = find_e_words(s, words);

    printf("%d\n", n);
    for (int i = 0; i < n; i++) {
        printf("%s\n", words[i]);
    }

    return 0;
}
