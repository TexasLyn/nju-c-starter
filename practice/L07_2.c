/*
 * L07_2 · 判断回文数 + 找孪生素数
 *
 * 【题目】（经典题）
 *   写两个函数，然后在 main 里使用它们：
 *
 *   函数 1：int huiwen(long n)
 *       判断 n 是不是回文数（正读反读一样）。
 *       是返回 1，不是返回 0。
 *
 *   函数 2：int prime(int n)
 *       判断 n 是不是素数。
 *       是返回 1，不是返回 0。
 *
 * 【main 的任务】
 *   读入一个整数 m，然后输出两行：
 *
 *   第一行：从 1 到 m 之间所有回文数的个数。
 *   第二行：从 1 到 m 之间所有孪生素数对的个数。
 *           （孪生素数：相差 2 的两个素数，比如 3 和 5、11 和 13）
 *
 * 【输入格式】
 *   一个整数 m，例如 100
 *
 * 【输出格式】
 *   两个整数，各占一行：
 *   18
 *   8
 *
 * 【样例验算（m = 100）】
 *   回文数：1,2,...,9（9 个）、11,22,...,99（9 个）= 18 个
 *
 *   孪生素数对：
 *       (3,5) (5,7) (11,13) (17,19) (29,31) (41,43) (59,61) (71,73) = 8 对
 *   注意 (5,7) 要算，因为 5 和 7 差 2，都是素数。
 *   数对的时候是数"有几对"，不是数"有几个素数"。
 *
 * 【函数 1 的思路】
 *   把一个数反过来读，看和原数是否相等。
 *   "反着读"就是用第 2 课学的拆数字方法重新组装：
 *
 *       long rev = 0;
 *       long t = n;
 *       while (t > 0) {
 *           rev = rev * 10 + t % 10;      (每次把新数字接到右边)
 *           t = t / 10;
 *       }
 *       return rev == n;
 *
 *   走一遍 121：
 *       t=121: rev = 0*10 + 1 = 1,      t = 12
 *       t=12:  rev = 1*10 + 2 = 12,     t = 1
 *       t=1:   rev = 12*10 + 1 = 121,   t = 0    ← rev 等于原数，是回文
 *
 *   🔸 `rev = rev * 10 + t % 10` 是"逐位拼数字"的标准写法，要记住。
 *
 * 【函数 2 的思路】
 *   这就是第 5 课学过的"先假设成立，发现问题就推翻"：
 *
 *       if (n < 2) return 0;              (0 和 1 不是素数)
 *       for (int i = 2; i * i <= n; i++) {
 *           if (n % i == 0) return 0;     (找到因子，不是素数)
 *       }
 *       return 1;
 *
 *   ⚠️ 循环条件写 i * i <= n 而不是 i < n：
 *       数学上只需要试到 √n 就够了（如果 n 有大于 √n 的因子，
 *       必定有一个小于 √n 的配对因子）。
 *       写 i < n 也对，就是慢很多。m 很大时差别明显。
 *
 * 【main 的思路】
 *   两件事各用一个循环，都在 1 到 m 范围内数数：
 *
 *       int cntHui = 0;
 *       for (long i = 1; i <= m; i++) {
 *           if (huiwen(i)) cntHui++;
 *       }
 *
 *       int cntTwin = 0;
 *       for (int i = 1; i <= m - 2; i++) {
 *           if (prime(i) && prime(i + 2)) cntTwin++;
 *       }
 *
 *   ⚠️ 孪生素数的循环上界是 m - 2，因为要看 i + 2 是否还在范围内。
 *
 * 【⚠️ 注意你写的函数必须"返回"而不是"打印"】
 *   题目说的是判断函数，应该 return 1 或 0。
 *   如果写成在里面 printf，就没法在 if 里用了。
 *   🔸 这是函数设计的基本原则：判断类函数返回布尔值，输出交给调用者。
 */

