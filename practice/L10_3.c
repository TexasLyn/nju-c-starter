/*
 * L10_3 · 用两个数组统计各数据出现次数
 *
 * 【题目】（经典题）
 *   读入 n 个整数，统计每种数据出现了多少次。
 *   要求用【两个数组】：一个存数据，一个存对应的次数。
 *
 * 【输入格式】
 *   第一行一个整数 n
 *   第二行 n 个整数
 *
 * 【输出格式】
 *   每种数据一行，格式 "数据 次数"，按【第一次出现的顺序】排列。
 *
 * 【样例】
 *   输入：
 *   10
 *   1 4 2 3 4 1 2 5 5 9
 *   输出：
 *   1 2
 *   4 1
 *   2 2
 *   3 1
 *   5 2
 *   9 1
 *
 *   解释：
 *       1 出现了 2 次（原数组里第 0 和第 5 个）
 *       4 出现了 1 次
 *       2 出现了 2 次
 *       3 出现了 1 次
 *       5 出现了 2 次
 *       9 出现了 1 次
 *   注意顺序是"第一次出现的顺序"，不是从小到大。
 *
 * 【思路：值数组 + 计数数组，同步增长】
 *
 *       int val[MAXN];          (存出现过的数据)
 *       int cnt[MAXN];          (存对应的次数)
 *       int m = 0;              (目前记录了多少种数据)
 *
 *       for (int i = 0; i < n; i++) {
 *           int j;
 *
 *           (在 val[0..m-1] 里找 a[i] 有没有出现过)
 *           for (j = 0; j < m; j++) {
 *               if (val[j] == a[i]) {
 *                   cnt[j]++;               (找到，次数加 1)
 *                   break;
 *               }
 *           }
 *
 *           if (j == m) {                       (循环走完了都没 break)
 *               val[m] = a[i];                  (新数据)
 *               cnt[m] = 1;
 *               m++;
 *           }
 *       }
 *
 * 【⚠️ 这里的技巧：用 j == m 判断"没找到"】
 *   内层 for 循环有两种结束方式：
 *       - 用 break 跳出：说明找到了，此时 j 是那个位置（j < m）
 *       - 条件 j < m 不成立自然结束：说明没找到，此时 j == m
 *
 *   所以循环结束后判断 j == m 就知道"有没有找到"。
 *   这是 C 里非常常用的写法，比再设一个 flag 变量更简洁。
 *
 *   🔸 注意 j 必须在 for【外面】声明，否则出了循环就用不了了。
 *
 * 【另一种等价写法（用 flag，更直观）】
 *
 *       int found = 0;
 *       for (int j = 0; j < m; j++) {
 *           if (val[j] == a[i]) {
 *               cnt[j]++;
 *               found = 1;
 *               break;
 *           }
 *       }
 *       if (!found) {
 *           val[m] = a[i];
 *           cnt[m] = 1;
 *           m++;
 *       }
 *
 *   两种都对，看你喜欢哪种。第一种更老练，第二种更好懂。
 *
 * 【为什么需要两个数组】
 *   因为要建立"数据 → 次数"的对应关系。
 *   一个数组只能存一列信息，两列信息就得两个数组，
 *   并且用【相同的下标】把它们关联起来：
 *       val[j] 和 cnt[j] 描述的是同一种数据。
 *   🔸 这个思想就是第 13 课"结构体"要解决的问题——
 *      把相关的数据打包在一起。现在先用两个数组凑合。
 */

#include <stdio.h>

#define MAXN 100

int main(void)
{
    int n;
    int a[MAXN];
    int val[MAXN];              /* 出现过的数据 */
    int cnt[MAXN];              /* 对应的次数 */
    int m = 0;                  /* 已记录的种数 */

    scanf("%d", &n);
    for (int i = 0; i < n; i++) {
        scanf("%d", &a[i]);
    }

    // TODO: 遍历 a，把每种数据记到 val/cnt 里

    // 输出
    for (int i = 0; i < m; i++) {
        printf("%d %d\n", val[i], cnt[i]);
    }

    return 0;
}
