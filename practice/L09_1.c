/*
 * L09_1 · 复数四则运算（结果存全局变量）
 *
 * 【题目】（经典题）
 *   实现复数的加、减、乘、除运算。结果通过【全局变量】返回。
 *
 *   复数形式：a + bi，其中 a 是实部，b 是虚部。
 *
 * 【函数要求】
 *       void cfun(char op, double a, double b, double c, double d)
 *
 *   参数：
 *       op —— 运算符，是 '+' '-' '*' '/' 之一
 *       (a, b) —— 第一个复数 a + bi
 *       (c, d) —— 第二个复数 c + di
 *   结果：
 *       写入【全局变量】 re 和 im
 *
 * 【运算公式】
 *   设 x = a + bi，y = c + di，则：
 *
 *       加法： re = a + c          im = b + d
 *       减法： re = a - c          im = b - d
 *       乘法： re = a*c - b*d      im = a*d + b*c
 *       除法： re = (a*c + b*d) / (c² + d²)
 *              im = (b*c - a*d) / (c² + d²)
 *
 * 【⚠️ 乘法公式为什么是这样】
 *   把 (a+bi)(c+di) 展开（注意 i² = -1）：
 *       ac + adi + bci + bdi²
 *     = ac + adi + bci - bd
 *     = (ac - bd) + (ad + bc)i
 *   所以实部是 ac - bd，虚部是 ad + bc。
 *
 * 【⚠️ 除法公式为什么是这样】
 *   分子分母同时乘以分母的共轭 (c - di)，分母就变成实数 c²+d²：
 *       (a+bi)/(c+di) = [(a+bi)(c-di)] / [(c+di)(c-di)]
 *   分母 (c+di)(c-di) = c² + d²
 *   分子 (a+bi)(c-di) = (ac+bd) + (bc-ad)i
 *
 * 【输入格式】
 *   一个运算符，然后是四个浮点数：
 *   + 1 2 3 4
 *   （表示计算 (1+2i) + (3+4i)）
 *
 * 【输出格式】
 *   两个浮点数，保留 6 位小数，用空格分隔，末尾换行。
 *   即使虚部是负数，也直接输出（不加括号、不加正号）。
 *
 * 【样例】
 *   输入 + 1 2 3 4   →  4.000000 6.000000
 *   输入 - 1 2 3 4   →  -2.000000 -2.000000
 *   输入 * 1 2 3 4   →  -5.000000 10.000000
 *   输入 / 1 2 3 4   →  0.440000 0.080000
 *
 * 【⚠️ 为什么题目要求用全局变量而不是指针】
 *   这是第 9 课的指定要求，目的是让你练习全局变量的用法。
 *   实际工程里更推荐用指针参数（第 8 课学的），因为那样函数是自包含的。
 *   两种方式你都要会写，上机题可能考任何一种。
 *
 * 【读运算符】
 *   用 scanf(" %c %lf %lf %lf %lf", &op, &a, &b, &c, &d);
 *   注意 %c 前面那个空格，第 3 课讲过——它会跳过前面的空白字符。
 *   如果漏了这个空格，%c 会读到输入流里的空白，op 就变成空格了。
 */

