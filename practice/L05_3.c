/*
 * L05_3 · 分解质因数
 *
 * 【题目】（经典题）
 *   读入一个正整数，把它分解成质因数相乘的形式输出。
 *
 * 【输入格式】
 *   一个正整数，例如 60
 *
 * 【输出格式】
 *   形如 n=p1*p2*...，质因数从小到大排列，末尾换行。
 *   例如输入 60，输出：
 *   60=2*2*3*5
 *
 * 【样例】
 *   输入 60    →  60=2*2*3*5
 *   输入 97    →  97=97        （97 本身是质数）
 *   输入 12    →  12=2*2*3
 *
 * 【思路：从小到大试除】
 *
 *   从 p = 2 开始，看 n 能不能被 p 整除：
 *     - 能整除：把 p 输出，然后 n = n / p，【p 不变】继续试
 *     - 不能整除：p 加 1，继续试
 *   直到 n 变成 1。
 *
 *   走一遍 60：
 *       p=2: 60 % 2 == 0 → 输出 2，n = 30
 *       p=2: 30 % 2 == 0 → 输出 2，n = 15
 *       p=2: 15 % 2 != 0 → p 变成 3
 *       p=3: 15 % 3 == 0 → 输出 3，n = 5
 *       p=3: 5 % 3 != 0  → p 变成 4
 *       p=4: 5 % 4 != 0  → p 变成 5
 *       p=5: 5 % 5 == 0  → 输出 5，n = 1
 *       n == 1，结束
 *   输出：2*2*3*5  ✓
 *
 * 【⚠️ 为什么内层用 while 而不是 if】
 *   因为同一个质因数可能出现多次（60 里有三个 2）。
 *   用 while 才能一次除干净。
 *
 *       for (int p = 2; p <= n; p++) {
 *           while (n % p == 0) {
 *               输出 p;
 *               n = n / p;          // n 变小了，所以 p <= n 的条件会自动收紧
 *           }
 *       }
 *
 *   注意循环条件 p <= n 里的 n 是【会变的】，所以 p 不需要试到原来的 n。
 *   比如 60，p 最大只试到 5。
 *
 * 【⚠️ 星号怎么输出】
 *   第一个质因数前面没有星号，后面的都有。所以需要一个标记：
 *
 *       int first = 1;                 // 1 表示"还没输出过"
 *       ...
 *       if (!first) printf("*");       // 不是第一个就先输出星号
 *       printf("%d", p);
 *       first = 0;                     // 之后都算"不是第一个"了
 */

