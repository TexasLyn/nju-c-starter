/*
 * L10_4 · 素数首尾交换，非素数位置不变
 *
 * 【题目】（经典题）
 *   读入 n 个整数。把所有【素数】按原来的顺序收集起来，
 *   首尾配对交换位置，然后放回它们在数组中的原位置。
 *   非素数的位置保持不动。
 *
 * 【输入格式】
 *   第一行一个整数 n
 *   第二行 n 个整数
 *
 * 【输出格式】
 *   处理后的数组，用空格分隔，末尾换行。
 *
 * 【样例】
 *   输入：
 *   8
 *   3 8 5 4 7 6 11 9
 *   输出：
 *   11 8 7 4 5 6 3 9
 *
 * 【样例详解（这道题务必看明白）】
 *
 *   原数组：   3   8   5   4   7   6   11  9
 *   下标：     0   1   2   3   4   5   6   7
 *   是素数？   是  否  是  否  是  否  是  否
 *
 *   第一步：把素数的【位置】和【值】收集起来（按顺序）
 *       位置：0, 2, 4, 6
 *       值：  3, 5, 7, 11
 *
 *   第二步：把这些值【首尾配对交换】
 *       3 ←→ 11     5 ←→ 7
 *       交换后：11, 7, 5, 3
 *
 *   第三步：按原来的位置放回去
 *       位置 0 放 11
 *       位置 2 放 7
 *       位置 4 放 5
 *       位置 6 放 3
 *
 *   结果：    11   8   7   4   5   6   3   9   ✓
 *             0    1   2   3   4   5   6   7
 *   非素数（8、4、6、9）都在原位没动。
 *
 * 【实现思路：收集 → 交换 → 放回】
 *
 *       int pos[MAXN];          (素数的位置)
 *       int val[MAXN];          (素数的值)
 *       int m = 0;              (素数的个数)
 *
 *       (第一步：收集)
 *       for (int i = 0; i < n; i++) {
 *           if (is_prime(a[i])) {
 *               pos[m] = i;
 *               val[m] = a[i];
 *               m++;
 *           }
 *       }
 *
 *       (第二步：首尾配对交换（在 val 数组里交换）)
 *       for (int i = 0; i < m / 2; i++) {
 *           int t = val[i];
 *           val[i] = val[m - 1 - i];
 *           val[m - 1 - i] = t;
 *       }
 *
 *       (第三步：放回原位置)
 *       for (int i = 0; i < m; i++) {
 *           a[pos[i]] = val[i];
 *       }
 *
 * 【⚠️ 为什么要同时记位置和值，不能只记位置？】
 *   如果只记位置，交换的时候就得在 a 上直接交换：
 *       a[pos[i]] 和 a[pos[m-1-i]] 交换
 *   这也行！而且更省一个数组。但仍需要一个 pos 数组。
 *
 *   两种写法都对：
 *       写法 A（记位置+值，分三步）：逻辑清楚，两个数组
 *       写法 B（只记位置，直接在 a 上交换）：省空间，代码短
 *
 *   下面给出写法 B，你可以对比着理解：
 *
 *       (收集位置)
 *       for (int i = 0; i < n; i++)
 *           if (is_prime(a[i])) pos[m++] = i;
 *
 *       (直接在 a 上按位置交换)
 *       for (int i = 0; i < m / 2; i++) {
 *           int t = a[pos[i]];
 *           a[pos[i]] = a[pos[m - 1 - i]];
 *           a[pos[m - 1 - i]] = t;
 *       }
 *
 * 【⚠️ 首尾交换的循环条件 i < m / 2】
 *   这是"反转数组"的标准写法。走一遍 m = 4：
 *       i=0: 交换 val[0] 和 val[3]
 *       i=1: 交换 val[1] 和 val[2]
 *       i=2: 2 < 2 不成立，停
 *   每个元素都只被交换一次，正好。
 *
 *   如果写成 i < m，就会交换两次（换回去了），等于没换。
 *   如果 m 是奇数（比如 5），m/2 = 2：
 *       i=0: 交换 val[0] 和 val[4]
 *       i=1: 交换 val[1] 和 val[3]
 *   中间的 val[2] 不用动（本来就在正中），正确。
 *
 * 【素数判断】
 *   用第 7 课写的 is_prime：
 *       int is_prime(int n) {
 *           if (n < 2) return 0;
 *           for (int i = 2; i * i <= n; i++)
 *               if (n % i == 0) return 0;
 *           return 1;
 *       }
 *   ⚠️ 注意 1 不是素数，所以要有 n < 2 这个判断。
 */

