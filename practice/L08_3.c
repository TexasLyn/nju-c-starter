/*
 * L08_3 · 用指针参数写 swap 函数
 *
 * 【题目】
 *   写一个函数 void swap(int *a, int *b)，交换两个整数变量的值。
 *   然后在 main 里读入两个整数，调用 swap 后输出它们（此时应该已经交换）。
 *
 * 【输入格式】
 *   两个整数，用空格分隔。
 *
 * 【输出格式】
 *   交换后的两个整数，用空格分隔，末尾换行。
 *
 * 【样例】
 *   输入 3 7   →   7 3
 *   输入 -1 5  →   5 -1
 *
 * 【为什么必须用指针】
 *   你在第 7 课学过：C 的参数是【值传递】，函数里改不了外面的变量。
 *
 *       void swap_bad(int a, int b)
 *       {
 *           int t = a;
 *           a = b;
 *           b = t;
 *           (交换的是两个副本，函数一结束副本就没了，外面毫无变化)
 *       }
 *
 *   要真的交换，必须传地址，让函数顺着地址去改原来的变量。
 *
 * 【怎么写】
 *
 *       void swap(int *a, int *b)
 *       {
 *           int t = *a;         (把 a 指向的那个变量的值，存起来)
 *           *a = *b;            (把 b 指向的值，写进 a 指向的地方)
 *           *b = t;             (把存好的值写进 b 指向的地方)
 *       }
 *
 * 【⚠️ 三个最容易写错的地方】
 *
 *   1. 忘了写 *：
 *          int t = a;       (✗ a 是地址（一串大数字），不是值)
 *          *a = *b;         (✗ 写成了"修改指针本身"，不是修改它指向的变量)
 *      【注意：漏 * 通常编译不报错！因为指针和整数都是数值，C 允许赋值。
 *        但结果完全错，甚至程序崩溃。这是指针题最危险的坑。】
 *
 *   2. 调用时忘了 &：
 *          swap(a, b);      (✗ 编译错误：传 int 给 int*)
 *          swap(&a, &b);    (✓)
 *
 *   3. 中间变量 t 的类型：
 *          int t = *a;      (✓ t 存的是"值"，是 int 不是 int*)
 *
 * 【验证方法】
 *   写完之后，故意把函数里的 * 都删掉（写成值传递版本），
 *   跑一下看结果——你会发现输出没变。这样能加深理解。
 */

