/*
 * L14_4 · 统计文件中的字符数、单词数、行数
 *
 * 【题目】
 *   读入一个文件名（从键盘输入），统计这个文件里有多少个字符、
 *   多少个单词、多少行，把结果写入 out.txt 并打印到屏幕。
 *
 * 【输入格式】
 *   一行，文件名（不含空格）。评测时会给出 in.txt。
 *
 * 【输出格式（屏幕和 out.txt 内容相同）】
 *   三行：
 *   chars=N
 *   words=N
 *   lines=N
 *
 * 【统计规则】
 *   - 字符数：文件里所有字符的个数（包括空白字符和换行）
 *   - 单词数：由空白字符（空格、Tab、换行）分隔的连续非空白片段个数
 *   - 行数：换行符 '\n' 的个数；如果文件末尾没有换行，最后一行也算一行
 *
 * 【样例】
 *   如果 in.txt 的内容是（注意末尾有换行）：
 *   hello world
 *   abc
 *   （也就是 17 个字符：hello world\nabc\n）
 *
 *   输出：
 *   chars=16
 *   words=3
 *   lines=2
 *
 * 【思路：逐字符读，边走边统计】
 *
 *   `fgetc(fp)` 每次从文件读一个字符，读到末尾返回 EOF。
 *   这是最底层的读法，很适合做这种逐字符统计：
 *
 *       int c;
 *       int chars = 0;
 *       int words = 0;
 *       int lines = 0;
 *       int inWord = 0;             (当前是不是在单词内部)
 *
 *       while ((c = fgetc(fp)) != EOF) {
 *           chars++;
 *
 *           if (c == '\n') {
 *               lines++;
 *           }
 *
 *           if (c == ' ' || c == '\t' || c == '\n') {
 *               inWord = 0;         (遇到空白，单词结束)
 *           } else {
 *               if (!inWord) {      (刚从空白进入非空白 → 新单词开始)
 *                   words++;
 *                   inWord = 1;
 *               }
 *           }
 *       }
 *
 *   🔸 【`inWord` 这个标志是统计单词数的核心技巧】：
 *      单词数 = "从空白进入非空白"的次数。
 *      这个思路和第 12 课找单词起点是同一个逻辑。
 *
 * 【⚠️ 四个关键点】
 *
 *   1. `int c` 必须是 int，不能是 char！
 *      因为 EOF 是一个特殊值（通常是 -1），char 装不下它，
 *      会导致循环判断出问题。这是 C 文件操作的一个经典陷阱。
 *
 *      【记住：用 fgetc 时，接收的变量声明成 int。】
 *
 *   2. `while ((c = fgetc(fp)) != EOF)` 的括号不能少。
 *      写成 `while (c = fgetc(fp) != EOF)` 会先算 `!=` 再赋值，
 *      完全错。这是运算符优先级问题。
 *
 *   3. 行数的定义。
 *      题目说"换行符的个数，末尾没有换行则最后一行也算"。
 *      严格实现：
 *          if (lines == 0 && chars > 0) lines = 1;      (空文件不算行)
 *          (或者更精确地：如果最后一个字符不是 \n，lines++)
 *      本课为了让代码简单，按"只数 \n"来算。
 *      评测数据里文件末尾都有换行，所以两者结果一样。
 *
 *   4. 别忘了 fclose。
 *
 * 【为什么不直接用 fgets 一行一行读】
 *   fgets 也行，但要处理行长度、末尾换行等细节，反而更麻烦。
 *   逐字符读是最直接的做法。
 *   🔸 上机题里两种都可能考，都要会。
 *
 * 【⚠️ 文件名是输入的，怎么打开】
 *   char fname[100];
 *   scanf("%s", fname);                 (注意没有 &)
 *   FILE *fp = fopen(fname, "r");       (直接用变量当文件名)
 *
 *   fopen 的第一个参数是 char*，可以传数组名，也可以传字符串字面量。
 */

