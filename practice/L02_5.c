/*
 * L02_5 · 四位正整数反序输出
 *
 * 【题目】（经典题）
 *   读入一个四位正整数，把它的数字反过来输出。
 *
 * 【输入格式】
 *   一个四位数，例如 1234
 *
 * 【输出格式】
 *   反序后的整数，占一行。例如 1234 应输出：
 *   4321
 *
 * 【重要】
 *   反序后按"整数"输出，所以末尾的 0 会消失（因为没有前导零的概念）。
 *   例如输入 1200，输出是 21，不是 0021。
 *
 * 【提示】
 *   方法是"先拆开，再拼起来"：
 *
 *       1234 % 10 = 4        ← 千位变个位
 *       1234 / 10 = 123
 *       123 % 10  = 3        ← 百位变十位
 *       123 / 10  = 12
 *       12 % 10   = 2        ← 十位变百位
 *       12 / 10   = 1        ← 个位变千位
 *
 *   然后组装：
 *       4 * 1000 + 3 * 100 + 2 * 10 + 1 = 4321
 *
 * 【另一种思路】
 *   换个顺序拆也行：先取千位，再取百位……
 *       1234 / 1000 = 1            ← 千位
 *       1234 / 100 % 10 = 2        ← 百位
 *       1234 / 10 % 10 = 3         ← 十位
 *       1234 % 10 = 4              ← 个位
 *   然后 1 + 2*10 + 3*100 + 4*1000 = 4321
 *   两种思路都对，挑一个你觉得顺的。
 */

#include <stdio.h>

int main(void)
{
    int n;
    int reversed = 0;

    scanf("%d", &n);

    // TODO: 拆开 n 的各位数字，组装成 reversed
    reversed = (n % 4 == 0) ? 4 : 0;
    printf("%d\n", reversed);

    return 0;
}
